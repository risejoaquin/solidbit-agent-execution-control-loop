"""SACL V1 Dual Deliverable Packaging Contract: SUMMARY.md & SUMMARY.json.

Enforces RESULT_PROTOCOL.md §7 and Decision Baseline #23:
1. SUMMARY.md (Human Review Format):
   - High-level verdict badge and run metadata.
   - Comprehensive agent status table: Agent | Status | Exit Code | Report | Verdict.
   - File collision and overlap report.
   - Immediate Next Safe Action.
2. SUMMARY.json (Machine Governance Format):
   - Strictly conforms to schemas/summary.schema.json.
   - Records implementation_authorized as boolean evidence (not authority).
   - Validates architecture_freeze_ready and ready_for_integration ('YES' | 'NO').
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from sacl.contracts.models import AgentResult, RunSummary
from sacl.contracts.schema_validator import SchemaValidator, get_default_validator

logger = logging.getLogger("sacl.results.summary")


class DualSummaryGenerator:
    """Generates and writes both human-facing SUMMARY.md and machine-facing SUMMARY.json."""

    def __init__(self, validator: Optional[SchemaValidator] = None) -> None:
        self.validator = validator or get_default_validator()

    def build_summary_model(
        self,
        run_id: str,
        package_id: str,
        project: str,
        status: str,
        ready_for_integration: str,
        agent_results: List[AgentResult],
        conflicting_files: Optional[List[str]] = None,
        documents_created: Optional[List[str]] = None,
        adrs_created: Optional[List[str]] = None,
        schemas_created: Optional[List[str]] = None,
        compatibility_findings: Optional[List[str]] = None,
        next_safe_action: str = "HUMAN_CODE_REVIEW",
        job_id: Optional[str] = None,
        architecture_freeze_ready: bool = True,
        implementation_authorized: bool = False,
        open_contradictions: int = 0,
        security_critical_unknowns: int = 0,
    ) -> RunSummary:
        """Constructs and validates the canonical RunSummary object.

        Raises:
            ContractValidationError: If payload fails summary.schema.json validation.
        """
        # Status normalization to schema enum: PASS, FAIL, BLOCKED, REVIEW_REQUIRED, DONE_REVIEW_REQUIRED
        norm_status = status.upper().strip()
        if norm_status in ("SUCCEEDED", "SUCCESS"):
            norm_status = "PASS"
        elif norm_status in ("FAILED", "ERROR"):
            norm_status = "FAIL"
        elif norm_status == "DONE_REVIEW_REQUIRED":
            norm_status = "DONE_REVIEW_REQUIRED"
        elif "REVIEW" in norm_status:
            norm_status = "REVIEW_REQUIRED"

        summary = RunSummary(
            run_id=run_id,
            package_id=package_id,
            job_id=job_id,
            project=project,
            status=norm_status,
            architecture_freeze_ready=architecture_freeze_ready,
            implementation_authorized=implementation_authorized,
            open_contradictions=open_contradictions,
            security_critical_unknowns=security_critical_unknowns,
            ready_for_integration=ready_for_integration,
            agent_results=list(agent_results),
            conflicting_files=list(conflicting_files or []),
            documents_created=list(documents_created or []),
            adrs_created=list(adrs_created or []),
            schemas_created=list(schemas_created or []),
            compatibility_findings=list(compatibility_findings or []),
            next_safe_action=next_safe_action,
            schema="solidbit.run-summary.v1",
        )

        # Validate against canonical summary.schema.json
        self.validator.validate_summary(summary.to_dict())
        return summary

    def format_markdown_summary(self, summary: RunSummary) -> str:
        """Constructs the canonical human-readable SUMMARY.md content."""
        verdict = summary.status

        lines = [
            f"# SACL EXECUTION RUN SUMMARY: {verdict}",
            "",
            "> **Generated by SolidBit Agent Execution Control Loop (SACL V1)**  ",
            f"> **Run ID:** `{summary.run_id}`  ",
            f"> **Package ID:** `{summary.package_id}`  ",
            f"> **Project:** `{summary.project}`  ",
            f"> **Ready For Integration:** `{summary.ready_for_integration}`  ",
            f"> **Implementation Authorized:** `{summary.implementation_authorized}`  ",
            "",
            "---",
            "",
            "## 1. Run Metadata",
            "",
            "| Field | Value |",
            "| :--- | :--- |",
            f"| **Run ID** | `{summary.run_id}` |",
            f"| **Job ID** | `{summary.job_id or 'N/A'}` |",
            f"| **Package ID** | `{summary.package_id}` |",
            f"| **Target Project** | `{summary.project}` |",
            f"| **Overall Verdict** | **`{summary.status}`** |",
            f"| **Ready for Integration** | `{summary.ready_for_integration}` |",
            f"| **Implementation Authorized** | `{summary.implementation_authorized}` (Evidence only) |",
            f"| **Architecture Freeze Ready** | `{summary.architecture_freeze_ready}` |",
            f"| **Open Contradictions** | `{summary.open_contradictions}` |",
            f"| **Security Critical Unknowns** | `{summary.security_critical_unknowns}` |",
            "",
            "---",
            "",
            "## 2. Agent Deliverables & Status",
            "",
            "| Agent | Status | Exit Code | Report Present | Verdict |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ]

        for ag in summary.agent_results:
            exit_str = str(ag.exitCode) if ag.exitCode is not None else "N/A"
            rep_str = "YES" if ag.reportExists else "NO"
            lines.append(f"| `{ag.agent}` | `{ag.status}` | `{exit_str}` | `{rep_str}` | **`{ag.verdict}`** |")

        lines.extend([
            "",
            "---",
            "",
            "## 3. Cross-Agent File Collisions & Modifications",
            "",
        ])

        if summary.conflicting_files:
            lines.append("> [!WARNING] File collisions detected across parallel agent branches!")
            lines.append("")
            lines.append("| Conflicting File Path |")
            lines.append("| :--- |")
            for cf in summary.conflicting_files:
                lines.append(f"| `{cf}` |")
        else:
            lines.append("No cross-agent file conflicts detected across parallel branches. Branch integration safe.")

        lines.extend([
            "",
            "---",
            "",
            "## 4. Deliverables Created",
            "",
        ])

        if summary.documents_created:
            lines.append(f"**Documents ({len(summary.documents_created)}):**")
            for doc in summary.documents_created:
                lines.append(f"- `{doc}`")
            lines.append("")

        if summary.adrs_created:
            lines.append(f"**Architecture Decision Records ({len(summary.adrs_created)}):**")
            for adr in summary.adrs_created:
                lines.append(f"- `{adr}`")
            lines.append("")

        if summary.schemas_created:
            lines.append(f"**Schemas ({len(summary.schemas_created)}):**")
            for sch in summary.schemas_created:
                lines.append(f"- `{sch}`")
            lines.append("")

        if summary.compatibility_findings:
            lines.append("### Compatibility Findings")
            for finding in summary.compatibility_findings:
                lines.append(f"- {finding}")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 5. Immediate Next Safe Action",
            "",
            f"**`{summary.next_safe_action}`**",
            "",
        ])

        return "\n".join(lines)

    def write_dual_summaries(
        self,
        summary: RunSummary,
        run_dir: Path,
    ) -> Tuple[Path, Path]:
        """Materializes SUMMARY.md and SUMMARY.json into the specified run directory.

        Returns:
            Tuple of (summary_md_path, summary_json_path).
        """
        run_dir.mkdir(parents=True, exist_ok=True)
        summary_md_path = run_dir / "SUMMARY.md"
        summary_json_path = run_dir / "SUMMARY.json"

        # Format and write SUMMARY.md
        md_content = self.format_markdown_summary(summary)
        summary_md_path.write_text(md_content, encoding="utf-8")

        # Format and write SUMMARY.json
        json_dict = summary.to_dict()
        with open(summary_json_path, "w", encoding="utf-8") as f:
            json.dump(json_dict, f, indent=2)

        logger.info(
            "Materialized dual summaries for run %s: %s, %s",
            summary.run_id,
            summary_md_path,
            summary_json_path,
        )
        return summary_md_path, summary_json_path


__all__ = ["DualSummaryGenerator"]
